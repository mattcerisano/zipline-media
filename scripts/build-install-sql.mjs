// Builds supabase/install/install.sql: the whole database in one paste.
//
//   node scripts/build-install-sql.mjs
//
// Concatenates supabase/install/base_schema.sql (the five original tables,
// which predate the migrations folder) with every file in
// supabase/migrations/ in filename order — the same order check-applied.mjs
// uses. Each migration records itself in schema_migrations as it runs, so a
// database installed this way reports "up to date" to that script afterwards.
//
// Re-run after adding a migration and commit the result; CI does not check
// that install.sql is current, this script is what keeps it so.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS_DIR = join(REPO_ROOT, 'supabase', 'migrations');
const INSTALL_DIR = join(REPO_ROOT, 'supabase', 'install');
const OUT = join(INSTALL_DIR, 'install.sql');

const migrations = readdirSync(MIGRATIONS_DIR).filter((f) => f.endsWith('.sql')).sort();

const banner = (title) => `\n\n-- ${'='.repeat(74)}\n-- ${title}\n-- ${'='.repeat(74)}\n\n`;
const body = (path) => readFileSync(path, 'utf8').replace(/\s+$/, '') + '\n';

let out = `-- Studio OS: complete database install for a fresh Supabase project.
--
-- GENERATED by scripts/build-install-sql.mjs — do not edit by hand. It is
-- supabase/install/base_schema.sql followed by the ${migrations.length} files in
-- supabase/migrations/, oldest first, exactly as they would be pasted one at a
-- time (docs/MIGRATIONS.md). Paste the whole thing into
-- Supabase → SQL Editor → New query and run it once. Safe to run twice.
--
-- What it sets up, besides the tables: row-level security on everything,
-- the storage buckets (avatars, branding, vault), realtime on the shared
-- tables, and a schema_migrations row per migration so
-- scripts/migrations/check-applied.mjs reports the database as current.
--
-- Not in here, by design:
--   * The first admin account — supabase/install/first_admin.sql.
--   * Sample data — supabase/install/sample_data.sql.
--   * The calendar-sync cron. That is a Vercel cron (vercel.json), created
--     automatically when the project deploys; it needs CRON_SECRET set.
--
-- Built ${new Date().toISOString().slice(0, 10)} from ${migrations[migrations.length - 1]}.
`;

out += banner('supabase/install/base_schema.sql');
out += body(join(INSTALL_DIR, 'base_schema.sql'));

for (const file of migrations) {
  out += banner(`supabase/migrations/${file}`);
  out += body(join(MIGRATIONS_DIR, file));
}

out += banner('Done');
out += `DO $$
DECLARE n INTEGER;
BEGIN
  SELECT count(*) INTO n FROM public.schema_migrations;
  RAISE NOTICE 'Studio OS installed: % of ${migrations.length} migrations recorded in schema_migrations.', n;
END $$;
`;

writeFileSync(OUT, out);
console.log(`Wrote ${OUT}: base schema + ${migrations.length} migrations, ${(out.length / 1024).toFixed(0)} KB.`);
